-- 1. Create PROFILES Table
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  employee_id VARCHAR(30) UNIQUE NOT NULL,
  full_name VARCHAR(100) NOT NULL,
  email VARCHAR(150),
  phone VARCHAR(20),
  address TEXT,
  job_title VARCHAR(100),
  department VARCHAR(100),
  joining_date DATE DEFAULT CURRENT_DATE,
  profile_picture_url TEXT,
  role VARCHAR(20) NOT NULL DEFAULT 'EMPLOYEE',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT check_role CHECK (role IN ('EMPLOYEE', 'ADMIN'))
);

-- 2. Create ATTENDANCE Table
CREATE TABLE IF NOT EXISTS public.attendance (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  attendance_date DATE NOT NULL DEFAULT CURRENT_DATE,
  check_in TIMESTAMPTZ,
  check_out TIMESTAMPTZ,
  status VARCHAR(20) DEFAULT 'PRESENT',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT check_attendance_status CHECK (status IN ('PRESENT', 'ABSENT', 'HALF_DAY', 'LEAVE')),
  CONSTRAINT unique_employee_date UNIQUE (employee_id, attendance_date)
);

-- 3. Create LEAVE_REQUESTS Table
CREATE TABLE IF NOT EXISTS public.leave_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  leave_type VARCHAR(20) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  remarks TEXT,
  status VARCHAR(20) DEFAULT 'PENDING',
  admin_comment TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT check_leave_type CHECK (leave_type IN ('PAID', 'SICK', 'UNPAID')),
  CONSTRAINT check_leave_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

-- 4. Create PAYROLL Table
CREATE TABLE IF NOT EXISTS public.payroll (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE UNIQUE,
  basic_salary NUMERIC(12,2) DEFAULT 0.00,
  allowances NUMERIC(12,2) DEFAULT 0.00,
  deductions NUMERIC(12,2) DEFAULT 0.00,
  net_salary NUMERIC(12,2) DEFAULT 0.00,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- INDEXES FOR PERFORMANCE
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_profiles_employee_id ON public.profiles(employee_id);
CREATE INDEX IF NOT EXISTS idx_profiles_role ON public.profiles(role);
CREATE INDEX IF NOT EXISTS idx_attendance_employee_id ON public.attendance(employee_id);
