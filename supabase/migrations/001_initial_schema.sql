-- Admin check helper function (SECURITY DEFINER to avoid RLS recursion)
CREATE OR REPLACE FUNCTION public.is_admin(user_uid UUID)
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
STABLE
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = user_uid AND role = 'ADMIN'
  );
$$;

-- Net salary auto-calculation trigger
CREATE OR REPLACE FUNCTION public.calculate_net_salary()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.net_salary := COALESCE(NEW.basic_salary, 0) + COALESCE(NEW.allowances, 0) - COALESCE(NEW.deductions, 0);
  NEW.updated_at := NOW();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_calc_payroll_net_salary ON public.payroll;
CREATE TRIGGER trg_calc_payroll_net_salary
BEFORE INSERT OR UPDATE ON public.payroll
FOR EACH ROW
EXECUTE FUNCTION public.calculate_net_salary();

-- Automatic Profile and Default Payroll creation on User Signup
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_employee_id TEXT;
  v_full_name TEXT;
  v_role TEXT;
  v_phone TEXT;
  v_address TEXT;
  v_department TEXT;
  v_job_title TEXT;
BEGIN
  -- Extract from raw_user_meta_data
  v_employee_id := COALESCE(NEW.raw_user_meta_data->>'employee_id', 'EMP-' || UPPER(SUBSTRING(NEW.id::text FROM 1 FOR 6)));
  v_full_name := COALESCE(NEW.raw_user_meta_data->>'full_name', SPLIT_PART(NEW.email, '@', 1));
  -- Enforce default EMPLOYEE role for public signups unless explicitly set by service role
  v_role := COALESCE(NEW.raw_user_meta_data->>'role', 'EMPLOYEE');
  IF v_role NOT IN ('EMPLOYEE', 'ADMIN') THEN
    v_role := 'EMPLOYEE';
  END IF;

  v_phone := NEW.raw_user_meta_data->>'phone';
  v_address := NEW.raw_user_meta_data->>'address';
  v_department := COALESCE(NEW.raw_user_meta_data->>'department', 'General');
  v_job_title := COALESCE(NEW.raw_user_meta_data->>'job_title', 'Staff Associate');

  -- Insert profile
  INSERT INTO public.profiles (
    id,
    employee_id,
    full_name,
    email,
    phone,
    address,
    job_title,
    department,
    joining_date,
    role
  ) VALUES (
    NEW.id,
    v_employee_id,
    v_full_name,
    NEW.email,
    v_phone,
    v_address,
    v_job_title,
    v_department,
    CURRENT_DATE,
    v_role
  ) ON CONFLICT (id) DO UPDATE SET
    email = EXCLUDED.email,
    full_name = COALESCE(EXCLUDED.full_name, public.profiles.full_name);

  -- Insert initial payroll record with default standard figures
  INSERT INTO public.payroll (
    employee_id,
    basic_salary,
    allowances,
    deductions
  ) VALUES (
    NEW.id,
    50000.00,
    5000.00,
    2500.00
  ) ON CONFLICT (employee_id) DO NOTHING;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

